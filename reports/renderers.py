"""Render ReportData as CSV, Excel (.xlsx) or PDF."""
import csv
import io

from django.utils import timezone
from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter
from reportlab.lib import colors
from reportlab.lib.enums import TA_RIGHT
from reportlab.lib.pagesizes import A4, landscape
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from .registry import INT, NUM, PCT, TEXT


def fmt(value, kind):
    """Display text for one cell (used by HTML, CSV and PDF)."""
    if value is None or value == "":
        return "—" if kind != TEXT else ""
    if kind == INT and isinstance(value, (int, float)):
        return f"{value:,.0f}"
    if kind == NUM and isinstance(value, (int, float)):
        return f"{value:,.1f}"
    if kind == PCT and isinstance(value, (int, float)):
        return f"{value:.1f}"
    return str(value)


def footer_line(user):
    who = (user.get_full_name() or user.username) if user else "system"
    return f"Generated by FaciliTrack on {timezone.localtime():%b %d, %Y %H:%M} for {who}"


# ---------------------------------------------------------------- CSV

def to_csv(report, user):
    out = io.StringIO()
    w = csv.writer(out)
    w.writerow([report.title])
    for label, value in report.params:
        w.writerow([label, value])
    w.writerow([footer_line(user)])
    w.writerow([])
    w.writerow([c.header for c in report.columns])
    for row in report.rows + ([report.totals] if report.totals else []):
        w.writerow(["" if v is None else (f"{v:.2f}" if isinstance(v, float) else v) for v in row])
    w.writerow([])
    for note in report.notes:
        w.writerow([note])
    return "﻿" + out.getvalue()  # BOM so Excel opens UTF-8 correctly


# ---------------------------------------------------------------- Excel

def to_xlsx(report, user):
    wb = Workbook()
    ws = wb.active
    ws.title = report.title[:31]
    ws.append([report.title])
    ws["A1"].font = Font(size=14, bold=True)
    for label, value in report.params:
        ws.append([label, value])
        ws.cell(ws.max_row, 1).font = Font(bold=True)
    ws.append([footer_line(user)])
    ws.cell(ws.max_row, 1).font = Font(italic=True, color="52514E")
    ws.append([])

    header_row = ws.max_row + 1
    ws.append([c.header for c in report.columns])
    for i, c in enumerate(report.columns, start=1):
        cell = ws.cell(header_row, i)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor="2A78D6")
        cell.alignment = Alignment(horizontal="right" if c.kind != TEXT else "left", vertical="center", wrap_text=True)
        ws.column_dimensions[get_column_letter(i)].width = max(c.width, len(c.header) + 2)

    number_formats = {INT: "#,##0", NUM: "#,##0.0", PCT: "0.0"}
    body = report.rows + ([report.totals] if report.totals else [])
    for r_index, row in enumerate(body):
        ws.append(row)
        excel_row = ws.max_row
        for i, c in enumerate(report.columns, start=1):
            cell = ws.cell(excel_row, i)
            if c.kind in number_formats and isinstance(cell.value, (int, float)):
                cell.number_format = number_formats[c.kind]
            if c.kind == TEXT and c.width >= 40:
                cell.alignment = Alignment(wrap_text=True, vertical="top")
            if report.totals and r_index == len(body) - 1:
                cell.font = Font(bold=True)
    ws.freeze_panes = ws.cell(header_row + 1, 1)
    ws.auto_filter.ref = f"A{header_row}:{get_column_letter(len(report.columns))}{header_row + len(report.rows)}"

    ws.append([])
    for note in report.notes:
        ws.append([note])
        ws.cell(ws.max_row, 1).font = Font(italic=True, color="52514E")
    buffer = io.BytesIO()
    wb.save(buffer)
    return buffer.getvalue()


# ---------------------------------------------------------------- PDF

def to_pdf(report, user):
    buffer = io.BytesIO()
    page = landscape(A4)
    doc = SimpleDocTemplate(buffer, pagesize=page, leftMargin=12 * mm, rightMargin=12 * mm,
                            topMargin=12 * mm, bottomMargin=14 * mm, title=report.title, author="FaciliTrack")
    styles = getSampleStyleSheet()
    small = ParagraphStyle("small", parent=styles["Normal"], fontSize=8, leading=10)
    cell = ParagraphStyle("cell", parent=small, fontSize=7.5, leading=9)
    cell_num = ParagraphStyle("cell_num", parent=cell, alignment=TA_RIGHT)
    head = ParagraphStyle("head", parent=cell, textColor=colors.white, fontName="Helvetica-Bold")
    head_num = ParagraphStyle("head_num", parent=head, alignment=TA_RIGHT)
    note_style = ParagraphStyle("note", parent=small, textColor=colors.HexColor("#52514e"))

    story = [Paragraph(report.title, styles["Title"])]
    meta = " &nbsp;·&nbsp; ".join(f"<b>{label}:</b> {_esc(value)}" for label, value in report.params)
    story += [Paragraph(meta, small), Spacer(1, 4 * mm)]

    total_width = page[0] - doc.leftMargin - doc.rightMargin
    weight = sum(c.width for c in report.columns)
    widths = [total_width * c.width / weight for c in report.columns]
    header = [Paragraph(_esc(c.header), head if c.kind == TEXT else head_num) for c in report.columns]
    body = report.rows + ([report.totals] if report.totals else [])
    data = [header] + [[Paragraph(_esc(fmt(v, c.kind)), cell if c.kind == TEXT else cell_num)
                        for v, c in zip(row, report.columns)] for row in body]
    if not report.rows:
        data.append([Paragraph("No data for these parameters.", cell)] + [""] * (len(report.columns) - 1))

    table = Table(data, colWidths=widths, repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#2a78d6")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#e1e0d9")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f7f7f5")]),
        ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]
    if report.totals:
        style += [("LINEABOVE", (0, -1), (-1, -1), 0.8, colors.HexColor("#52514e")),
                  ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#eeeeea"))]
    table.setStyle(TableStyle(style))
    story.append(table)
    if report.notes:
        story.append(Spacer(1, 4 * mm))
        story += [Paragraph(_esc(n), note_style) for n in report.notes]

    footer = footer_line(user)

    def draw_footer(canvas, _doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.HexColor("#898781"))
        canvas.drawString(doc.leftMargin, 7 * mm, footer)
        canvas.drawRightString(page[0] - doc.rightMargin, 7 * mm, f"Page {_doc.page}")
        canvas.restoreState()

    doc.build(story, onFirstPage=draw_footer, onLaterPages=draw_footer)
    return buffer.getvalue()


def _esc(text):
    return str(text).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
